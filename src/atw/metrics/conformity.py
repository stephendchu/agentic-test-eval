"""Human-free taste eval: indistinguishability from the maintainer's real test.

The repo's MERGED test is a human-accepted artifact — git history is our panel of
engineers, no recruiting needed. We ask a blind judge to tell the generated test
from the real merged one. If it can't (rate -> 0.5), the generated test is
"repo-native". Per arm, a LOWER distinguish-rate = more native taste.

This also validates the judge: if it reliably recovers the real merged test over
a generic draft, it is calibrated to real repo taste without human labels.
"""

from __future__ import annotations

from atw.metrics.behavioral import _claude_json, _extract_json

JUDGE_MODEL = "claude-sonnet-4-6"

DISTINGUISH_PROMPT = """Two pytest tests were written for the SAME code change in a \
repository. ONE was written by a maintainer of that repository and merged; the \
OTHER was generated by an AI. Decide which is the maintainer's, judging only by \
how well it fits the repository's conventions, idioms, and style.

<test_1>
{t1}
</test_1>

<test_2>
{t2}
</test_2>

Respond with ONLY JSON: {{"maintainer": 1 or 2, "confidence": 0.0-1.0, "tell": "<the giveaway, one phrase>"}}"""


def _real_position(swapped: bool) -> int:
    """Where the real merged test sits after the random swap (1 or 2)."""
    return 2 if swapped else 1


def judge_distinguish(merged: str, generated: str, rng, model: str = JUDGE_MODEL,
                      max_chars: int = 4000) -> dict:
    """Blind: can the judge pick the real merged test? Returns whether it did."""
    swapped = rng.random() < 0.5
    t1, t2 = (generated, merged) if swapped else (merged, generated)
    prompt = DISTINGUISH_PROMPT.format(t1=t1[:max_chars], t2=t2[:max_chars])
    data = _claude_json(prompt, model)
    if data is None:
        return {"ok": False, "error": "no json"}
    if data.get("_timeout"):
        return {"ok": False, "rate_limited": True, "reset_hint": "timeout (likely throttled)"}
    result = data.get("result", "") or ""
    if "session limit" in result.lower() or "usage limit" in result.lower():
        return {"ok": False, "rate_limited": True, "reset_hint": result.strip()[:200]}
    ans = _extract_json(result)
    pick = ans.get("maintainer")
    real = _real_position(swapped)
    return {
        "ok": True,
        "judge_correct": pick == real,   # True = judge caught the AI (less native)
        "confidence": ans.get("confidence"),
        "tell": ans.get("tell", ""),
        "swapped": swapped,
        "cost_usd_equiv": data.get("total_cost_usd"),
    }
